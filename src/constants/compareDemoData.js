// ── 업로드 파일명 → A/B 방향 맞추기(2026-10-12) ──
// 정책 비교에서 PDF를 반대 칸에 올려도(A=미래적금, B=도약계좌) 화면의 A/B가 올린 파일과 일치하도록
// 데이터의 a↔b를 통째로 바꾼다. 판정 키워드는 정책명에서 "청년"을 뺀 부분(도약계좌·미래적금)과 그 앞 두 글자.
const norm = (s) => String(s || '').replace(/\s+/g, '');
const keywords = (name) => {
    const core = norm(name).replace(/^청년/, '');
    return [core, core.slice(0, 2)].filter(Boolean);
};
const mentions = (fileName, side) => keywords(side.name).some((k) => norm(fileName).includes(k));

// A칸 파일이 B 정책을, 또는 B칸 파일이 A 정책을 가리키면(그리고 A칸이 A 정책을 가리키지 않으면) 뒤집는다.
export function shouldSwapCompare(data, fileNameA, fileNameB) {
    const aIsA = mentions(fileNameA, data.a);
    const aIsB = mentions(fileNameA, data.b);
    const bIsA = mentions(fileNameB, data.a);
    if (aIsA) return false;
    return aIsB || bIsA;
}

// a↔b를 바꾼 사본. swapped 플래그는 "내 조건 확인" 결과(a=도약 판정, b=미래 판정)를 같이 뒤집는 데 쓴다.
export function swapCompareSides(data) {
    const flip = (o) => ({ ...o, a: o.b, b: o.a });
    return {
        ...data,
        a: data.b,
        b: data.a,
        highlights: data.highlights.map(flip),
        rows: data.rows.map(flip),
        swapped: !data.swapped,
    };
}

